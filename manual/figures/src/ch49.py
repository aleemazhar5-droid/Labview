# 7. Modulation classification of synthetic I/Q signals: cumulant features + classifiers
MODS = ["BPSK", "QPSK", "8PSK", "16APSK", "16QAM", "64QAM"]


def constellation(name):
    if name.endswith("PSK") and not name.endswith("APSK"):
        M = {"BPSK": 2, "QPSK": 4, "8PSK": 8}[name]
        return np.exp(1j * (2 * np.pi * np.arange(M) / M + (np.pi / 4 if M == 4 else 0)))
    if name == "16APSK":
        r1, r2 = 1.0, 2.75
        return np.r_[r1 * np.exp(1j * (np.pi / 4 + np.pi / 2 * np.arange(4))),
                     r2 * np.exp(1j * (np.pi / 12 + np.pi / 6 * np.arange(12)))]
    M = int(name[:-3])
    m = int(np.sqrt(M))
    lv = np.arange(m) * 2 - (m - 1)
    return (lv[:, None] + 1j * lv[None, :]).ravel()


def iq_batch(mod, n_ex, n_sym, snr_db, rng):
    c = constellation(mod)
    c = c / np.sqrt(np.mean(np.abs(c) ** 2))
    x = c[rng.integers(0, len(c), (n_ex, n_sym))]
    ph = rng.uniform(0, 2 * np.pi, (n_ex, 1))
    fo = rng.uniform(-3e-4, 3e-4, (n_ex, 1))
    x = x * np.exp(1j * (ph + 2 * np.pi * fo * np.arange(n_sym)))
    g = rng.uniform(0.5, 2.0, (n_ex, 1))                       # unknown receive gain
    n = (rng.standard_normal((n_ex, n_sym)) + 1j * rng.standard_normal((n_ex, n_sym))) * np.sqrt(
        10 ** (-snr_db / 10) / 2)
    return g * (x + n)


def cum_features(y):
    """Phase- and gain-invariant features: normalised higher-order cumulants and amplitude statistics."""
    y = y - y.mean(1, keepdims=True)
    m20 = np.mean(y ** 2, 1)
    m21 = np.mean(np.abs(y) ** 2, 1)
    m40 = np.mean(y ** 4, 1)
    m41 = np.mean(y ** 3 * np.conj(y), 1)
    m42 = np.mean(np.abs(y) ** 4, 1)
    m60 = np.mean(y ** 6, 1)
    m63 = np.mean(np.abs(y) ** 6, 1)
    m80 = np.mean(y ** 8, 1)
    c40 = m40 - 3 * m20 ** 2
    c41 = m41 - 3 * m20 * m21
    c42 = m42 - np.abs(m20) ** 2 - 2 * m21 ** 2
    c63 = m63 - 9 * m42 * m21 + 12 * m21 ** 3
    a = np.abs(y) / np.sqrt(m21)[:, None]
    F = np.stack([np.abs(m20) / m21, np.abs(c40) / m21 ** 2, np.abs(c41) / m21 ** 2, c42.real / m21 ** 2,
                  np.abs(m60) / m21 ** 3, c63.real / m21 ** 3, np.abs(m80) / m21 ** 4, a.std(1),
                  stats.kurtosis(a, axis=1), np.percentile(a, 90, axis=1) - np.percentile(a, 10, axis=1)], 1)
    return F


