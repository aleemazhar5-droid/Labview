# 2-3. Synthetic telemetry with injected anomalies; three detectors
DT_MIN = 1.0            # one sample per minute
P_ORB = 96.0            # orbital period (min)
ECL = 0.36              # eclipse fraction of the orbit
UNMOD = 0.15            # amplitude of unmodelled variations (fraction of a typical channel spread)
NAMES = ["Battery voltage (V)", "Battery temp. (°C)", "Bus current (A)", "Panel temp. (°C)", "Wheel speed (rpm)",
         "Heater duty (%)"]


def tm_normal(n, rng, t0=0.0):
    """Six correlated housekeeping channels driven by the orbit (sunlit/eclipse), a payload mode and slow seasons."""
    t = t0 + np.arange(n) * DT_MIN
    ph = (t % P_ORB) / P_ORB
    sun = (ph < 1 - ECL).astype(float)
    sun_s = signal.lfilter([0.25], [1, -0.75], sun)                     # smoothed illumination
    season = 0.5 + 0.5 * np.sin(2 * np.pi * t / (14 * 1440.0))          # 14-day beta-angle cycle
    # payload mode: on for 20 min in some orbits (commanded, known to the ground)
    orbit = np.floor(t / P_ORB).astype(int)
    mode_on = ((orbit % 3 == 0) & (ph > 0.15) & (ph < 0.36)).astype(float)
    # state of charge: charges in sun, discharges in eclipse and with payload
    load = 2.0 + 1.6 * mode_on + 0.3 * (1 - sun)
    soc = np.empty(n)
    s = 0.85
    for i in range(n):
        s += (0.0042 * sun[i] * (1.0 - s) / 0.15 - 0.0011 * load[i]) * DT_MIN
        s = min(max(s, 0.3), 1.0)
        soc[i] = s
    cur = load + 0.05 * rng.standard_normal(n)
    vbat = 26.0 + 6.0 * (soc - 0.8) + 0.8 * sun_s - 0.25 * mode_on + 0.04 * rng.standard_normal(n)
    heater = np.clip(40 - 30 * sun_s + 10 * (1 - season) + 2.0 * rng.standard_normal(n), 0, 100)
    tbat = 12.0 + 3.0 * sun_s + 1.5 * season + 1.2 * mode_on + 0.02 * heater + 0.12 * rng.standard_normal(n)
    tpan = -60 + 120 * sun_s + 8 * season + 1.0 * rng.standard_normal(n)
    wheel = 1500 + 400 * np.sin(2 * np.pi * ph * 2 + 0.3) + 150 * mode_on + 60 * season + 8 * rng.standard_normal(n)
    X = np.stack([vbat, tbat, cur, tpan, wheel, heater], 1)
    # unmodelled slow variations (albedo, ageing, environment): AR(1) with a 3-hour time constant
    a = np.exp(-DT_MIN / 180.0)
    drift = signal.lfilter([np.sqrt(1 - a * a)], [1, -a], rng.standard_normal((n, 6)), axis=0)
    X = X + UNMOD * drift * np.array([0.9, 1.2, 0.35, 45.0, 180.0, 9.0])
    ctx = np.stack([np.sin(2 * np.pi * ph), np.cos(2 * np.pi * ph), np.sin(4 * np.pi * ph), np.cos(4 * np.pi * ph),
                    mode_on, season], 1)
    return X, ctx


def inject(X, rng, n_point=14, n_ctx=12, n_drift=8):
    """Point spikes, contextual swaps (values from the wrong part of the orbit) and slow drifts."""
    X = X.copy()
    n, C = X.shape
    lab = np.zeros(n, int)          # 0 normal, 1 point, 2 contextual, 3 drift
    events = []
    rng_ = X.max(0) - X.min(0)
    used = np.zeros(n, bool)

    def free(a, b):
        return not used[max(a - 120, 0):min(b + 120, n)].any()

    k = 0
    while k < n_point:
        i = int(rng.integers(200, n - 200))
        if not free(i, i + 1):
            continue
        c = int(rng.integers(0, C))
        X[i, c] += rng.choice([-1, 1]) * rng.uniform(0.25, 0.9) * rng_[c]
        lab[i] = 1
        used[i] = True
        events.append((1, i, i + 1, c))
        k += 1
    k = 0
    while k < n_ctx:
        d = int(rng.integers(20, 50))
        i = int(rng.integers(200, n - 300))
        if not free(i, i + d):
            continue
        c = int(rng.choice([0, 1, 3, 4, 5]))
        shift = int(P_ORB * rng.uniform(0.35, 0.65))
        X[i:i + d, c] = X[i - shift:i - shift + d, c]         # plausible values, wrong orbital phase
        lab[i:i + d] = 2
        used[i:i + d] = True
        events.append((2, i, i + d, c))
        k += 1
    k = 0
    while k < n_drift:
        d = int(rng.integers(360, 1080))
        i = int(rng.integers(200, n - d - 200))
        if not free(i, i + d):
            continue
        c = int(rng.choice([0, 1, 2, 4]))
        X[i:i + d, c] += np.linspace(0, 1, d) * rng.choice([-1, 1]) * rng.uniform(0.15, 0.35) * rng_[c]
        lab[i:i + d] = 3
        used[i:i + d] = True
        events.append((3, i, i + d, c))
        k += 1
    return X, lab, events


def smooth_max(z, w=5):
    """Moving average over w samples of the per-channel scores, then the largest across channels."""
    k = np.ones(w) / w
    zs = np.apply_along_axis(lambda c: np.convolve(c, k, mode="same"), 0, z)
    return zs.max(1)


@lru_cache(maxsize=1)
def tm_experiment():
    from sklearn.ensemble import IsolationForest
    rng = np.random.default_rng(49)
    ntr, nte = 14 * 1440, 14 * 1440
    Xtr, Ctr = tm_normal(ntr, rng)
    Xte0, Cte = tm_normal(nte, rng, t0=ntr * DT_MIN)
    Xte, lab, events = inject(Xte0, rng)
    mu, sd = Xtr.mean(0), Xtr.std(0)
    Ztr, Zte = (Xtr - mu) / sd, (Xte - mu) / sd
    C = Xtr.shape[1]
    # (a) fixed limits: training min/max widened by 5 % of range; score = largest normalised distance from mid-band
    lo, hi = Xtr.min(0), Xtr.max(0)
    mid, half = (lo + hi) / 2, (hi - lo) / 2 * 1.05
    s_lim = (np.abs(Xte - mid) / half).max(1)
    # (b) learned predictive model: each channel from the other channels + orbit phase + commanded mode (numpy MLP)
    res_tr, res_te = np.zeros_like(Ztr), np.zeros_like(Zte)
    for c in range(C):
        oth = [j for j in range(C) if j != c]
        Ftr = np.hstack([Ztr[:, oth], Ctr])
        Fte = np.hstack([Zte[:, oth], Cte])
        P = mlp_init([Ftr.shape[1], 24, 24, 1], rng)
        P = mlp_train(P, Ftr, Ztr[:, c], 12, 3e-3, rng, bs=128)
        res_tr[:, c] = mlp_fwd(P, Ftr)[-1][:, 0] - Ztr[:, c]
        res_te[:, c] = mlp_fwd(P, Fte)[-1][:, 0] - Zte[:, c]
    rsd = res_tr.std(0)
    s_pred = (np.abs(res_te) / rsd).max(1)
    s_pred_tr = (np.abs(res_tr) / rsd).max(1)
    # (c) isolation forest on values + orbit context + first differences
    def feats(Z, Cx):
        dZ = np.vstack([np.zeros((1, Z.shape[1])), np.diff(Z, axis=0)])
        return np.hstack([Z, Cx[:, :5], dZ])
    iso = IsolationForest(n_estimators=300, max_samples=1024, random_state=0).fit(feats(Ztr, Ctr))
    s_iso = -iso.score_samples(feats(Zte, Cte))
    out = dict(Xte=Xte, Xte0=Xte0, lab=lab, events=events, scores=dict(limits=s_lim, predictive=s_pred,
               iforest=s_iso), lo=lo, hi=hi, rsd=rsd, s_pred_tr=s_pred_tr)
    return out


def roc_curve_np(score, y):
    o = np.argsort(-score)
    ys = y[o]
    tp = np.cumsum(ys) / ys.sum()
    fp = np.cumsum(1 - ys) / (1 - ys).sum()
    return np.r_[0, fp], np.r_[0, tp]


def event_recall(score, lab, events, fpr):
    """Threshold set so that a fraction fpr of normal samples alarm; an event counts if any sample in it alarms."""
    thr = np.quantile(score[lab == 0], 1 - fpr)
    hit = {1: [], 2: [], 3: []}
    delay = []
    for typ, a, b, c in events:
        al = np.where(score[a:b] > thr)[0]
        hit[typ].append(len(al) > 0)
        if typ == 3 and len(al):
            delay.append(al[0] / (b - a))
    return {k: np.mean(v) for k, v in hit.items()}, thr, (np.mean(delay) if delay else np.nan)


