# 8. Adaptive coding and modulation over a synthetic Ka-band rain-fade year
# DVB-S2 MODCODs: (name, ideal Es/N0 dB, spectral efficiency bit/symbol), ETSI EN 302 307-1 Table 13
MODCODS = [("QPSK 1/4", -2.35, 0.490), ("QPSK 1/3", -1.24, 0.656), ("QPSK 2/5", -0.30, 0.789),
           ("QPSK 1/2", 1.00, 0.989), ("QPSK 3/5", 2.23, 1.188), ("QPSK 2/3", 3.10, 1.322),
           ("QPSK 3/4", 4.03, 1.487), ("QPSK 4/5", 4.68, 1.587), ("QPSK 5/6", 5.18, 1.655),
           ("8PSK 3/5", 5.50, 1.780), ("8PSK 2/3", 6.62, 1.981), ("8PSK 3/4", 7.91, 2.228),
           ("16APSK 2/3", 8.97, 2.637), ("16APSK 3/4", 10.21, 2.967), ("16APSK 4/5", 11.03, 3.166),
           ("16APSK 5/6", 11.61, 3.300), ("16APSK 8/9", 12.89, 3.523), ("32APSK 3/4", 12.73, 3.703),
           ("32APSK 4/5", 13.64, 3.952), ("32APSK 5/6", 14.28, 4.120), ("32APSK 8/9", 15.69, 4.398),
           ("32APSK 9/10", 16.05, 4.453)]
MODCODS = [m for m in MODCODS if not any(o[1] <= m[1] and o[2] > m[2] for o in MODCODS)]   # drop dominated ones
MC_T = np.array([m[1] for m in MODCODS])
MC_E = np.array([m[2] for m in MODCODS])
ESN0_CLEAR = 16.0     # clear-sky Es/N0 (dB)
IMPL = 0.5            # implementation margin (dB)
STEP_S = 10.0
DELAY = 3             # decision uses measurements 30 s old (loop delay and averaging)
DELAY_LONG = 30       # ... or 5 min old (e.g. planning ahead)
FADE_BINS = [-1, 0.3, 0.6, 1, 1.5, 2, 3, 4, 6, 8, 12, 1e9]


def best_modcod(esn0):
    """Index of the most efficient MODCOD whose threshold is below esn0 (-1 if none)."""
    return np.searchsorted(MC_T, np.asarray(esn0), side="right") - 1


@lru_cache(maxsize=1)
def rain_year():
    rng = np.random.default_rng(5)
    n = int(365 * 86400 / STEP_S)
    # rain on/off: two-state Markov chain, mean event 1.2 h, rain ~5 % of the time
    p_on, p_off = STEP_S / (23 * 3600), STEP_S / (1.2 * 3600)
    state = np.zeros(n, np.int8)
    i = 0
    while i < n:                                               # alternate geometric dry and rain spells
        i += int(rng.geometric(p_on))
        d = int(rng.geometric(p_off))
        state[i:i + d] = 1
        i += d
    env = signal.lfilter([1 - np.exp(-STEP_S / 600)], [1, -np.exp(-STEP_S / 600)], state.astype(float))
    a = np.exp(-2e-4 * STEP_S)                                 # Maseng-Bakken log-normal process, beta = 2e-4 /s
    X = signal.lfilter([np.sqrt(1 - a * a)], [1, -a], rng.standard_normal(n))
    A = env * np.exp(np.log(1.0) + 1.0 * X)                    # rain fade (dB), median 1 dB in rain
    scint = signal.lfilter([np.sqrt(1 - 0.5 ** 2)], [1, -0.5], rng.standard_normal(n)) * 0.15
    deg = A + scint                                            # total degradation of Es/N0 (dB)
    return deg, state


def acm_run(deg, decision_esn0, margin):
    """Throughput (bit/symbol) and outage flags when the MODCOD is chosen from decision_esn0 minus margins."""
    k = best_modcod(decision_esn0 - IMPL - margin)
    actual = ESN0_CLEAR - deg
    eff = np.where(k >= 0, MC_E[np.clip(k, 0, None)], 0.0)
    out = (k < 0) | (actual - IMPL < MC_T[np.clip(k, 0, None)])
    return np.where(out, 0.0, eff), out


def acm():
    deg, state = rain_year()
    n = len(deg)
    esn0 = ESN0_CLEAR - deg
    a01 = np.quantile(deg, 0.999)
    a1 = np.quantile(deg, 0.99)
    # fixed MODCOD for 99.9 % availability
    kf = best_modcod(np.array([ESN0_CLEAR - a01 - IMPL]))[0]
    thr_ccm, eff_ccm = MC_T[kf], MC_E[kf]
    avail_ccm = np.mean(esn0 - IMPL >= thr_ccm)
    # ideal ACM (perfect, instantaneous knowledge)
    th_ideal, _ = acm_run(deg, esn0, 0.0)
    ntr = int(90 * 86400 / STEP_S)
    test = slice(ntr, n)
    ideal_mean = th_ideal[test].mean()

    def lagged(x, d):
        return np.r_[np.full(d, x[0]), x[:-d]]

    curves = {}
    margins = np.linspace(0, 4.0, 41)
    for d in (DELAY, DELAY_LONG):
        dec = ESN0_CLEAR - lagged(deg, d)
        th, un = zip(*[(lambda r: (r[0].mean(), r[1].mean()))(acm_run(deg[test], dec[test], mg)) for mg in margins])
        curves[("fixed", d)] = (np.array(th), np.array(un), margins)
    # learned, state-dependent margin: conditional quantile of the fade change over the delay, estimated on the
    # first 90 days in cells of (current fade, recent trend) -- a look-up-table form of quantile regression
    d = DELAY_LONG
    lag = lagged(deg, d)
    slope = lag - lagged(deg, d + 6)
    cell = (np.digitize(lag, FADE_BINS) - 1) * 3 + (np.digitize(slope, [-0.3, 0.3]))
    delta = deg - lag
    alphas = 1 - np.logspace(-1.0, -5.0, 25)
    th, un = [], []
    for al in alphas:
        q = np.full(cell.max() + 1, 3.0)
        for c in range(cell.max() + 1):
            mm = cell[:ntr] == c
            if mm.sum() > 50:
                q[c] = np.quantile(delta[:ntr][mm], al)
        r = acm_run(deg[test], (ESN0_CLEAR - lag - np.maximum(q[cell], 0))[test], 0.0)
        th.append(r[0].mean())
        un.append(r[1].mean())
    curves[("learned", d)] = (np.array(th), np.array(un), alphas)
    print(f"ACM fade exceeded 1%: {a1:.2f} dB, 0.1%: {a01:.2f} dB; rain {state.mean() * 100:.1f}% of time")
    print(f"ACM CCM {MODCODS[kf][0]} thr {thr_ccm} eff {eff_ccm} avail {avail_ccm * 100:.3f}%; ideal ACM mean "
          f"{ideal_mean:.3f} b/sym = x{ideal_mean / (eff_ccm * avail_ccm):.2f}")
    res = {}
    for key, (th_, un_, par) in curves.items():
        ok = np.where(un_ <= 1e-3)[0]
        j = ok[np.argmax(th_[ok])]
        res[key] = th_[j]
        print(f"ACM {key}: best at <=0.1% unavailable: param {par[j]:.5f} -> {th_[j]:.3f} b/sym "
              f"(x{th_[j] / eff_ccm:.2f} vs CCM)")
    kc = best_modcod(np.array([ESN0_CLEAR - IMPL]))[0]
    print(f"ACM clear-sky MODCOD {MODCODS[kc][0]} eff {MC_E[kc]}")
    past = ESN0_CLEAR - lagged(deg, DELAY)
    th_m = margins[np.argmax(curves[("fixed", DELAY)][1] <= 1e-3)]

    fig = plt.figure(figsize=(7.0, 3.2))
    gs = fig.add_gridspec(2, 2, width_ratios=[1.15, 1], height_ratios=[1, 1], hspace=0.12, wspace=0.62)
    # pick the rain event containing the year's deepest fade within a 6-hour window
    i0 = int(np.argmax(np.where(deg > 10, 0, deg)))
    w0 = max(i0 - int(3 * 3600 / STEP_S), 0)
    wsl = slice(w0, w0 + int(6 * 3600 / STEP_S))
    tt = (np.arange(n)[wsl] - w0) * STEP_S / 3600
    ax = fig.add_subplot(gs[0, 0])
    ax.plot(tt, esn0[wsl], color=NAVY, lw=0.8)
    ax.axhline(thr_ccm + IMPL, color=ORANGE, lw=0.9, ls="--")
    ax.text(0.05, thr_ccm + IMPL + 0.4, f"fixed {MODCODS[kf][0]} needs {thr_ccm + IMPL:.1f} dB", fontsize=6.0,
            color=ORANGE, va="bottom")
    ax.set_ylabel("Es/N0 (dB)", fontsize=7.0)
    ax.tick_params(labelbottom=False, labelsize=6.3)
    ax.set_xlim(0, 6)
    panel_tag(ax, "a")
    ax = fig.add_subplot(gs[1, 0])
    t_d, o_d = acm_run(deg[wsl], past[wsl], th_m)
    ax.step(tt, t_d, color=BLUE, lw=0.9, where="post", label=f"ACM (30 s old data, {th_m:.1f} dB margin)")
    ax.step(tt, np.where(esn0[wsl] - IMPL >= thr_ccm, eff_ccm, 0), color=ORANGE, lw=1.1, where="post",
            label="fixed MODCOD")
    ax.set_ylabel("bit/symbol", fontsize=7.0)
    ax.set_xlabel("Hours", fontsize=7.0)
    ax.set_xlim(0, 6)
    ax.set_ylim(0, 4.9)
    ax.legend(fontsize=6.0, loc="center left", bbox_to_anchor=(0.0, 0.62), ncol=1)
    ax.tick_params(labelsize=6.3)
    ax = fig.add_subplot(gs[:, 1])
    bars = [("Fixed MODCOD\n(" + MODCODS[kf][0] + ")", eff_ccm * avail_ccm, ORANGE),
            ("ACM, 5 min old data,\nfixed margin", res[("fixed", DELAY_LONG)], VIOLET),
            ("ACM, 5 min old data,\nlearned margin", res[("learned", DELAY_LONG)], GREEN),
            ("ACM, 30 s old data,\nfixed margin", res[("fixed", DELAY)], BLUE),
            ("Ideal ACM\n(perfect knowledge)", ideal_mean, GREY)]
    y = np.arange(len(bars))[::-1]
    ax.barh(y, [b_[1] for b_ in bars], color=[b_[2] for b_ in bars], height=0.62)
    for yy, b_ in zip(y, bars):
        ax.text(b_[1] + 0.05, yy, f"{b_[1]:.2f}  (×{b_[1] / (eff_ccm * avail_ccm):.2f})", va="center",
                fontsize=6.3)
    ax.set_yticks(y)
    ax.set_yticklabels([b_[0] for b_ in bars], fontsize=6.3)
    ax.set_xlim(0, 5.6)
    ax.set_xlabel("Mean throughput at ≥ 99.9 % availability (bit/symbol)", fontsize=6.8)
    ax.tick_params(axis="x", labelsize=6.3)
    ax.grid(axis="y", lw=0)
    panel_tag(ax, "b", x=-0.02)
    foot(fig, f"Synthetic Ka-band downlink, one year at 10 s steps: rain 5 % of the time with log-normal fades "
         f"(Maseng–Bakken model; exceeded 1 % of the time: {a1:.1f} dB, 0.1 %: {a01:.1f} dB) plus scintillation; "
         f"clear-sky Es/N0 {ESN0_CLEAR:.0f} dB; DVB-S2 thresholds (ETSI EN 302 307-1) plus 0.5 dB implementation "
         "margin. (b) Each ACM scheme uses the smallest safety margin that keeps unavailability at or below 0.1 %; the "
         "learned margin is a quantile of the fade change predicted from the current fade and its trend (trained on "
         "the first 90 days, scored on the rest).", y=0.0, width=150)
    fig.subplots_adjust(left=0.08, right=0.99, top=0.95, bottom=0.31)
    save(fig, "ch49_acm")


