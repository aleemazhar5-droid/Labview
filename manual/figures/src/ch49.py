# 9. Laser-mesh routing in a Walker-delta constellation (networkx)
C_KM_S = 299792.458


def walker_graph(P_=72, S_=22, F_=39, alt=550.0, inc=53.0):
    import networkx as nx
    a = RE + alt
    i = np.radians(inc)
    pos = {}
    for p_ in range(P_):
        raan = 2 * np.pi * p_ / P_
        for s_ in range(S_):
            u = 2 * np.pi * (s_ / S_ + F_ * p_ / (P_ * S_))
            pos[(p_, s_)] = a * np.array([np.cos(raan) * np.cos(u) - np.sin(raan) * np.sin(u) * np.cos(i),
                                          np.sin(raan) * np.cos(u) + np.cos(raan) * np.sin(u) * np.cos(i),
                                          np.sin(u) * np.sin(i)])
    G = nx.Graph()
    for (p_, s_), r in pos.items():
        G.add_node((p_, s_), r=r)
    for p_ in range(P_):
        for s_ in range(S_):
            for q in [(p_, (s_ + 1) % S_), ((p_ + 1) % P_, s_)]:      # intra-plane and cross-plane neighbours
                d = np.linalg.norm(pos[(p_, s_)] - pos[q])
                G.add_edge((p_, s_), q, km=d, isl=True)
    return G, pos


def add_city(G, pos, name, lat, lon, el_min=25.0):
    la, lo = np.radians(lat), np.radians(lon)
    r0 = RE * np.array([np.cos(la) * np.cos(lo), np.cos(la) * np.sin(lo), np.sin(la)])
    G.add_node(name, r=r0)
    for k, r in pos.items():
        d = r - r0
        el = np.degrees(np.arcsin(d @ (r0 / RE) / np.linalg.norm(d)))
        if el > el_min:
            G.add_edge(name, k, km=np.linalg.norm(d), isl=False)
    return r0


def gc_km(lat1, lon1, lat2, lon2):
    p1, p2, dl = np.radians(lat1), np.radians(lat2), np.radians(lon2 - lon1)
    return RE * np.arccos(np.sin(p1) * np.sin(p2) + np.cos(p1) * np.cos(p2) * np.cos(dl))


