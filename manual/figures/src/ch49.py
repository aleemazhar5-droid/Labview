# 6. Contact scheduling: greedy rules versus a mixed-integer programme
RE, MU = 6378.137, 398600.4418
WE = 7.2921159e-5


def passes_for(n_planes=6, per_plane=6, alt=550.0, inc=97.6, el_min=10.0, step=30.0, hours=24.0, seed=3):
    stations = [("Svalbard", 78.23, 15.40), ("Inuvik", 68.32, -133.55), ("Awarua", -46.53, 168.38)]
    rng = np.random.default_rng(seed)
    a = RE + alt
    n_mot = np.sqrt(MU / a ** 3)
    t = np.arange(0, hours * 3600 + 1, step)
    sats = []
    for p in range(n_planes):
        raan = np.radians(360.0 / n_planes / 2 * p)          # planes spread over 180 deg (sun-synchronous-like)
        for k in range(per_plane):
            u0 = 2 * np.pi * (k / per_plane + p / (n_planes * per_plane))
            sats.append((raan, u0))
    i = np.radians(inc)
    st_xyz = []
    for nm, la, lo in stations:
        la, lo = np.radians(la), np.radians(lo)
        st_xyz.append(RE * np.array([np.cos(la) * np.cos(lo), np.cos(la) * np.sin(lo), np.sin(la)]))
    P = []          # (sat, station, t_start, t_end)
    for s_, (raan, u0) in enumerate(sats):
        u = u0 + n_mot * t
        x = a * (np.cos(raan) * np.cos(u) - np.sin(raan) * np.sin(u) * np.cos(i))
        y = a * (np.sin(raan) * np.cos(u) + np.cos(raan) * np.sin(u) * np.cos(i))
        z = a * np.sin(u) * np.sin(i)
        th = -WE * t                                      # inertial -> Earth-fixed
        xe, ye = x * np.cos(th) - y * np.sin(th), x * np.sin(th) + y * np.cos(th)
        r = np.stack([xe, ye, z], 1)
        for g, r0 in enumerate(st_xyz):
            d = r - r0
            el = np.degrees(np.arcsin((d @ (r0 / RE)) / np.linalg.norm(d, axis=1)))
            vis = el > el_min
            edges = np.diff(np.r_[0, vis.astype(int), 0])
            for a0, a1 in zip(np.where(edges == 1)[0], np.where(edges == -1)[0]):
                if (a1 - a0) * step >= 180:
                    P.append((s_, g, t[a0] / 60.0, t[a1 - 1] / 60.0))
    demand = rng.uniform(100, 300, len(sats))              # GB waiting per satellite per day
    return P, demand, [s[0] for s in stations], len(sats)


RATE = 3.0      # GB per minute (400 Mbit/s X-band)
TURN = 2.0      # minutes between passes on one antenna


def greedy(P, demand, order):
    busy_g = {}
    busy_s = {}
    left = demand.copy()
    chosen = []
    for j in order:
        s_, g, a, b = P[j]
        if left[s_] <= 0:
            continue
        if any(a < bb + TURN and b + TURN > aa for aa, bb in busy_g.get(g, [])):
            continue
        if any(a < bb and b > aa for aa, bb in busy_s.get(s_, [])):
            continue
        busy_g.setdefault(g, []).append((a, b))
        busy_s.setdefault(s_, []).append((a, b))
        left[s_] -= min(left[s_], RATE * (b - a))
        chosen.append(j)
    return chosen, demand - left


def milp_schedule(P, demand, lam=0.25):
    from scipy.optimize import milp, LinearConstraint, Bounds
    from scipy.sparse import lil_matrix
    nP, nS = len(P), len(demand)
    nv = nP + nS + 1                                   # x_p, y_s, z
    rows = []
    # antenna and satellite conflicts: for each pass start, passes overlapping that instant sum to <= 1
    for j, (s_, g, a, b) in enumerate(P):
        rows.append([k for k, (s2, g2, a2, b2) in enumerate(P) if g2 == g and a2 <= a < b2 + TURN])
        rows.append([k for k, (s2, g2, a2, b2) in enumerate(P) if s2 == s_ and a2 <= a < b2])
    rows = [sorted(set(r)) for r in rows if len(r) > 1]
    rows = [list(r) for r in {tuple(r) for r in rows}]
    A = lil_matrix((len(rows) + 2 * nS, nv))
    for r, ks in enumerate(rows):
        for k in ks:
            A[r, k] = 1
    lb = [-np.inf] * len(rows)
    ub = [1.0] * len(rows)
    for s_ in range(nS):                                # y_s - sum rate*dur*x <= 0 ;  z*D_s - y_s <= 0
        r = len(rows) + s_
        A[r, nP + s_] = 1
        for k, (s2, g2, a2, b2) in enumerate(P):
            if s2 == s_:
                A[r, k] = -RATE * (b2 - a2)
        lb.append(-np.inf)
        ub.append(0.0)
        r2 = len(rows) + nS + s_
        A[r2, nv - 1] = demand[s_]
        A[r2, nP + s_] = -1
        lb.append(-np.inf)
        ub.append(0.0)
    c = np.zeros(nv)
    c[nP:nP + nS] = -1.0
    c[-1] = -lam * demand.sum()
    integ = np.r_[np.ones(nP), np.zeros(nS + 1)]
    bounds = Bounds(np.zeros(nv), np.r_[np.ones(nP), demand, 1.0])
    res = milp(c, constraints=LinearConstraint(A.tocsr(), lb, ub), integrality=integ, bounds=bounds,
               options=dict(time_limit=45, mip_rel_gap=5e-3))
    x = res.x[:nP] > 0.5
    return [j for j in range(nP) if x[j]], res.x[nP:nP + nS], res


