# Lorenz-96: dx_k/dt = (x_{k+1} - x_{k-2}) x_{k-1} - x_k + F ; 40 sites, F = 8; 0.05 time units = 6 h
K96, F96, DT96, NSUB = 40, 8.0, 0.01, 5
STEPS_PER_DAY = 4


def l96_tend(x, F=F96):
    return (np.roll(x, -1, -1) - np.roll(x, 2, -1)) * np.roll(x, 1, -1) - x + F


def l96_rk4(x, n, F=F96):
    for _ in range(n):
        k1 = l96_tend(x, F)
        k2 = l96_tend(x + 0.5 * DT96 * k1, F)
        k3 = l96_tend(x + 0.5 * DT96 * k2, F)
        k4 = l96_tend(x + DT96 * k3, F)
        x = x + DT96 / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
    return x


def l96_run(x0, nsamp, F=F96):
    out = np.empty((nsamp,) + x0.shape)
    x = x0
    for i in range(nsamp):
        x = l96_rk4(x, NSUB, F)
        out[i] = x
    return out


W96 = 4   # stencil half-width of the learned local model


def stencil(X):
    return np.stack([np.roll(X, -j, -1) for j in range(-W96, W96 + 1)], -1)


@lru_cache(maxsize=1)
def l96_setup():
    rng = np.random.default_rng(1)
    x = F96 + rng.normal(0, 1, (8, K96))
    x = l96_rk4(x, 2000)
    train = l96_run(x, 1500).transpose(1, 0, 2)          # 8 trajectories x 1500 samples (6 h) = 3000 days
    test = l96_run(l96_rk4(F96 + rng.normal(0, 1, K96), 2000), 4000)
    mu, sd = float(train.mean()), float(train.std())
    X = stencil((train[:, :-1] - mu) / sd).reshape(-1, 2 * W96 + 1).astype(np.float32)
    dY = (train[:, 1:] - train[:, :-1]).reshape(-1)
    dsd = float(dY.std())
    Y = (dY / dsd).astype(np.float32)
    P = mlp_init([2 * W96 + 1, 48, 48, 1], rng)
    P = mlp_train(P, X, Y, 10, 2e-3, rng, bs=256)
    resid = mlp_fwd(P, X)[-1][:, 0] - Y
    print(f"L96: {train.shape[0] * train.shape[1]} training states ({train.shape[0] * train.shape[1] / 4:.0f} days),"
          f" {len(X)} stencil examples; one-step normalised MSE {np.mean(resid ** 2):.5f}; clim std {sd:.2f}")

    def emu(xx):
        s = stencil((xx - mu) / sd)
        sh = s.shape
        return xx + mlp_fwd(P, s.reshape(-1, sh[-1]).astype(np.float32))[-1][:, 0].reshape(sh[:-1]) * dsd

    return dict(rng=rng, train=train, test=test, mu=mu, sd=sd, emu=emu, nparam=sum(W.size + b.size for W, b in P))


def roll(step, x0, L):
    out = [x0]
    x = x0
    for _ in range(L):
        x = step(x)
        out.append(x)
    return np.stack(out, -2)


