def dst():
    rng = np.random.default_rng(11)
    H = 4 * 365 * 24
    t = np.arange(H)

    def ar1(n, ph, sig):
        e = rng.normal(0, sig * np.sqrt(1 - ph ** 2), n)
        y = np.zeros(n)
        for i in range(1, n):
            y[i] = ph * y[i - 1] + e[i]
        return y
    V = 380 + np.zeros(H)
    for ph0, amp in [(0.2, 250), (0.65, 180)]:      # two recurrent high-speed streams (27-day rotation)
        x = ((t / 24.0 / 27.0) - ph0) % 1.0
        V += amp * np.exp(-0.5 * ((x - 0.05) / 0.04) ** 2) * (x < 0.3)
    V += ar1(H, 0.98, 40)
    Bz = ar1(H, 0.85, 2.0)
    cir = np.clip(np.gradient(V), 0, None)
    cs = np.convolve(cir, np.ones(18) / 18, "same")
    Bz *= 1 + 1.5 * cs / cs.max()
    for s in rng.choice(np.arange(100, H - 200), int(4 * 365 / 18), replace=False):   # CMEs
        v = rng.uniform(450, 1100)
        dur = int(rng.uniform(10, 36))
        bmin = rng.gamma(2.0, 4.5) * (v / 600)
        V[s:s + dur + 12] = np.maximum(V[s:s + dur + 12], v * np.r_[np.ones(dur), np.linspace(1, 0.7, 12)])
        Bz[s:s + dur] += rng.choice([1, -1], p=[0.35, 0.65]) * bmin * np.sin(np.pi * np.arange(dur) / dur)
    V = np.clip(V, 280, 1200)
    VBs = V * np.clip(-Bz, 0, None) * 1e-3          # mV/m
    D = np.zeros(H)
    d = 0.0
    for i in range(H):                              # O'Brien & McPherron (2000) Burton-type model, 1-h steps
        e = VBs[i]
        Q = -4.4 * (e - 0.49) if e > 0.49 else 0.0
        d += Q - d / (2.4 * np.exp(9.74 / (4.69 + e)))
        D[i] = d
    P = 1.6726e-6 * 5.0 * V ** 2 * np.clip(1 + 0.2 * rng.normal(size=H), 0.3, None)
    Dst = D + 7.26 * np.sqrt(P) - 11 + rng.normal(0, 2.0, H)
    ntr = 3 * 365 * 24
    print(f"dst: min {Dst.min():.0f} nT (train min {Dst[:ntr].min():.0f}, test min {Dst[ntr:].min():.0f}); "
          f"time below -50 nT {(Dst < -50).mean() * 100:.1f} %, below -100 nT {(Dst < -100).mean() * 100:.1f} %")
    lags = 6

    def build(h, use_sw):
        idx = np.arange(24, H - h)
        X = [Dst[idx - k] for k in range(lags)]
        if use_sw:   # L1 data at hour i describe the solar wind that reaches the magnetosphere at i + 1
            X += [VBs[idx + 1 - k] for k in range(lags + 1)] + [np.sqrt(P[idx + 1])]
        return np.stack(X, 1), Dst[idx + h], idx
    leads = [1, 2, 3, 4, 5, 6]
    res = {k: [] for k in ["pers", "ar", "arx", "mlp"]}
    rs = {k: [] for k in res}
    keep = {}
    for h in leads:
        for use in [False, True]:
            X, y, idx = build(h, use)
            tr, te = idx < ntr, idx >= ntr
            Xa = np.c_[X, np.ones(len(X))]
            wv = np.linalg.solve(Xa[tr].T @ Xa[tr] + 1e-3 * np.eye(Xa.shape[1]), Xa[tr].T @ y[tr])
            pl = Xa[te] @ wv
            k = "arx" if use else "ar"
            res[k].append(np.sqrt(np.mean((pl - y[te]) ** 2)))
            st = y[te] < -50
            rs[k].append(np.sqrt(np.mean((pl - y[te])[st] ** 2)))
            if use and h == 3:
                keep["arx"] = pl
        pers = Dst[idx[te]]
        res["pers"].append(np.sqrt(np.mean((pers - y[te]) ** 2)))
        rs["pers"].append(np.sqrt(np.mean((pers - y[te])[st] ** 2)))
        Xs = X.astype(np.float32)
        P_ = mlp_init([X.shape[1], 32, 32, 1], np.random.default_rng(h))
        mu, sd = Xs[tr].mean(0), Xs[tr].std(0) + 1e-6
        yres = (y - X[:, 0]).astype(np.float32)
        ysd = float(yres[tr].std())
        P_ = mlp_train(P_, (Xs[tr] - mu) / sd, yres[tr] / ysd, 40, 3e-3, np.random.default_rng(h), bs=256, decay=0.93)
        pm = mlp_fwd(P_, (Xs[te] - mu) / sd)[-1][:, 0] * ysd + X[te, 0]
        res["mlp"].append(np.sqrt(np.mean((pm - y[te]) ** 2)))
        rs["mlp"].append(np.sqrt(np.mean((pm - y[te])[st] ** 2)))
        if h == 3:
            keep.update(pers=pers, mlp=pm, y=y[te], idx=idx[te])
    for k in res:
        print(f"dst {k}: RMSE {np.round(res[k], 1)} storm-time {np.round(rs[k], 1)}")
    for k in ["ar", "arx", "mlp"]:
        ss = 1 - (np.array(res[k]) / np.array(res["pers"])) ** 2
        sss = 1 - (np.array(rs[k]) / np.array(rs["pers"])) ** 2
        print(f"dst skill vs persistence {k}: all {np.round(ss, 2)} storm {np.round(sss, 2)}")
    fig, axs = plt.subplots(1, 3, figsize=(7.0, 2.7), gridspec_kw=dict(width_ratios=[1.5, 1, 1]))
    ax = axs[0]
    y = keep["y"]
    i0 = int(np.argmin(y))
    sl = slice(i0 - 24, i0 + 48)
    hrs = np.arange(-24, 48)
    ax.plot(hrs, y[sl], color=INK, lw=2.0, label="Observed")
    ax.plot(hrs, keep["pers"][sl], color=GREY, lw=1.2, ls="--", label="Persistence (3 h)")
    ax.plot(hrs, keep["mlp"][sl], color=ORANGE, lw=1.4, label="MLP + L1 (3 h)")
    ax.set_xlim(-24, 48)
    ax.set_xlabel("Hours from storm peak", fontsize=7.2)
    ax.set_ylabel("Dst (nT)", fontsize=7.2)
    ax.legend(fontsize=6.0, loc="lower right")
    panel_tag(ax, "a")
    sty = {"pers": (GREY, "Persistence", "--"), "ar": (GOLD, "Linear AR, Dst only", "-"),
           "arx": (BLUE, "Linear ARX + L1 wind", "-"), "mlp": (ORANGE, "MLP + L1 wind", "-")}
    for ax, dd, ttl in [(axs[1], res, "All hours"), (axs[2], rs, "Storm hours (Dst < -50 nT)")]:
        for k in ["pers", "ar", "arx", "mlp"]:
            c, lab, ls = sty[k]
            ax.plot(leads, dd[k], color=c, lw=1.6, ls=ls, marker="o", ms=2.5, label=lab)
        ax.set_xlabel("Lead time (h)", fontsize=7.2)
        ax.set_ylabel("RMSE (nT)", fontsize=7.2)
        ax.set_title(ttl, fontsize=7.4)
        ax.set_xticks(leads)
    axs[1].legend(fontsize=5.9, loc="upper left")
    panel_tag(axs[1], "b")
    panel_tag(axs[2], "c")
    for a_ in axs:
        a_.tick_params(labelsize=6.8)
    foot(fig, "Four years of hourly synthetic solar wind (recurrent streams, CMEs, random Bz) drive the O'Brien-McPherron "
              "Burton-type Dst model with pressure correction and 2 nT noise. Years 1-3 train, year 4 tests; inputs: 6 "
              "hours of past Dst, and for ARX/MLP 7 hours of L1 VBs (one hour ahead of Earth) and dynamic pressure.",
         width=135)
    fig.tight_layout(rect=(0, 0.11, 1, 1), w_pad=0.8)
    save(fig, "ch47_dst")


