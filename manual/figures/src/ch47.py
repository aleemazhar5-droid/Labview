    starts = np.linspace(0, 3900 - L, nst).astype(int)
    truth = np.stack([test[s:s + L + 1] for s in starts])
    ana = truth[:, 0] + rng.normal(0, sig_a, truth[:, 0].shape)
    ctrl = roll(emu, ana, L)
    xe = ana[:, None, :] + rng.normal(0, sig_a, (nst, M, K96))
    ens = roll(emu, xe, L)                                   # nst, M, L+1, K
    # stochastic version: add model-error noise each step
    sig_q = 0.06

    def emu_noise(x):
        return emu(x) + rng.normal(0, sig_q, x.shape)
    ens_q = roll(emu_noise, xe, L)
    mean, mean_q = ens.mean(1), ens_q.mean(1)

    def rm(f):
        return np.sqrt(((f - truth) ** 2).mean((0, 2)))

    def spr(e):
        return np.sqrt(e.var(1, ddof=1).mean((0, 2)))

    def act(f):
        return np.sqrt(((f - mu) ** 2).mean((0, 2)))
