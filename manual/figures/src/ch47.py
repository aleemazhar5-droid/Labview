def flare():
    from sklearn.linear_model import LogisticRegression
    from sklearn.ensemble import HistGradientBoostingClassifier
    from sklearn.metrics import roc_curve
    rng = np.random.default_rng(21)
    n = 40000
    z = rng.normal(0, 1, n)                      # hidden free magnetic energy
    w = rng.normal(0, 1, n)                      # unobserved trigger
    X = np.c_[22.0 + 0.6 * z + 0.36 * rng.normal(size=n),         # log10 total unsigned flux (Mx)
              3.0 + 0.9 * z + 0.48 * rng.normal(size=n),           # log R (flux near polarity inversion line)
              0.7 * z + 0.56 * rng.normal(size=n),                 # current helicity (standardised)
              0.5 * z + 0.72 * rng.normal(size=n),                 # mean shear angle (standardised)
              rng.poisson(np.exp(-1.2 + 0.8 * z))]                 # flares in previous 24 h
    p = 1 / (1 + np.exp(-(-6.5 + 2.6 * z + 0.5 * w)))
    yv = rng.random(n) < p
    ntr = int(0.6 * n)                           # chronological split: first 60 % train
    Xtr, ytr, Xte, yte = X[:ntr], yv[:ntr], X[ntr:], yv[ntr:]
    lr_ = LogisticRegression(max_iter=1000, class_weight="balanced").fit(Xtr, ytr)
    gb = HistGradientBoostingClassifier(max_iter=200, learning_rate=0.05, random_state=0).fit(Xtr, ytr)
    ps = {"Logistic regression": lr_.predict_proba(Xte)[:, 1], "Gradient boosting": gb.predict_proba(Xte)[:, 1]}
    print(f"flare: base rate {yv.mean() * 100:.2f} %; test events {yte.sum()} of {len(yte)}")
    fig, axs = plt.subplots(1, 3, figsize=(7.0, 2.6))
    ax = axs[0]
    ths = np.linspace(0.01, 0.99, 197)
    best = {}
    for (name, pp), c in zip(ps.items(), [BLUE, ORANGE]):
        fpr, tpr, _ = roc_curve(yte, pp)
        ax.plot(fpr, tpr, color=c, lw=1.5, label=name)
        tss = [((pp >= t) & yte).sum() / yte.sum() - ((pp >= t) & ~yte).sum() / (~yte).sum() for t in ths]
        best[name] = (ths[int(np.argmax(tss))], max(tss), tss)
        print(f"flare {name}: max TSS {max(tss):.3f} at threshold {ths[int(np.argmax(tss))]:.2f}")
    ax.plot([0, 1], [0, 1], color=GREY, lw=0.8, ls=":")
    ax.set_xlabel("False-alarm rate (POFD)", fontsize=7.2)
    ax.set_ylabel("Probability of detection", fontsize=7.2)
    ax.legend(fontsize=6.0, loc="lower right")
    panel_tag(ax, "a")
    ax = axs[1]
    ax.plot(ths, best["Logistic regression"][2], color=BLUE, lw=1.6, label="TSS")
    pp = ps["Logistic regression"]
    hss = []
    for t in ths:
        a = ((pp >= t) & yte).sum()
        b = ((pp >= t) & ~yte).sum()
        c_ = ((pp < t) & yte).sum()
        d = ((pp < t) & ~yte).sum()
        hss.append(2 * (a * d - b * c_) / ((a + c_) * (c_ + d) + (a + b) * (b + d)))
    ax.plot(ths, hss, color=BLUE, lw=1.1, ls="--", label="HSS")
    ax.set_xlabel("Threshold on logistic output", fontsize=7.2)
    ax.set_ylabel("Skill score", fontsize=7.2)
    ax.set_ylim(0, 0.9)
    ax.legend(fontsize=6.0, loc="upper right")
    panel_tag(ax, "b")
    # contingency table at the TSS-optimal threshold of the logistic model
    t0 = best["Logistic regression"][0]
    a = int(((pp >= t0) & yte).sum())
    b = int(((pp >= t0) & ~yte).sum())
    c_ = int(((pp < t0) & yte).sum())
    d = int(((pp < t0) & ~yte).sum())
    print(f"flare table at {t0:.2f}: hits {a} false alarms {b} misses {c_} correct negatives {d}; "
          f"POD {a / (a + c_):.3f} POFD {b / (b + d):.3f} TSS {a / (a + c_) - b / (b + d):.3f} precision {a / (a + b):.3f}")
    # base-rate dependence: same POD and POFD, different climatological event rates
    pod, pofd = a / (a + c_), b / (b + d)
    rates = np.logspace(-3, -0.7, 60)
    prec = pod * rates / (pod * rates + pofd * (1 - rates))
    hssr = []
    for r in rates:
        A, B, C, D = pod * r, pofd * (1 - r), (1 - pod) * r, (1 - pofd) * (1 - r)
        hssr.append(2 * (A * D - B * C) / ((A + C) * (C + D) + (A + B) * (B + D)))
    ax = axs[2]
    ax.semilogx(rates * 100, np.full_like(rates, pod - pofd), color=BLUE, lw=1.6, label="TSS")
    ax.semilogx(rates * 100, hssr, color=BLUE, lw=1.1, ls="--", label="HSS")
    ax.semilogx(rates * 100, prec, color=VIOLET, lw=1.4, label="Precision")
    ax.axvline(yte.mean() * 100, color=GREY, lw=0.8, ls=":")
    ax.set_xlabel("Event rate in sample (%)", fontsize=7.2)
    ax.set_ylabel("Score", fontsize=7.2)
    ax.set_ylim(0, 1)
    ax.legend(fontsize=6.0, loc="upper left")
    panel_tag(ax, "c")
    for r in [0.5, 5.0, 20.0]:
        rr = r / 100
        print(f"flare base rate {r} %: precision {pod * rr / (pod * rr + pofd * (1 - rr)):.3f}")
    for a_ in axs:
        a_.tick_params(labelsize=6.8)
    foot(fig, "Synthetic region-days: five magnetogram-like features driven by a hidden free-energy variable; flare "
              "(M class or above within 24 h) drawn from a logistic law with an unobserved trigger term. First 60 % "
              "for training, last 40 % for testing. (c) Fixed detection and false-alarm rates of the logistic model.",
         width=130)
    fig.tight_layout(rect=(0, 0.09, 1, 1), w_pad=1.0)
    save(fig, "ch47_flare")


