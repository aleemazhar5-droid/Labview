# Two-layer energy-balance model with a weak state-dependent feedback
C_UP, C_DP, LAM0, GAMMA, ALPHA, F2X = 7.3, 106.0, 1.13, 0.73, 0.035, 3.7


def ebm(F, rng=None):
    T = TD = 0.0
    out = []
    for f in F:
        for _ in range(4):
            lam = LAM0 - ALPHA * T
            dT = (f - lam * T - GAMMA * (T - TD)) / C_UP
            dTD = GAMMA * (T - TD) / C_DP
            T += 0.25 * dT
            TD += 0.25 * dTD
        out.append(T)
    out = np.array(out)
    if rng is not None:
        e = np.zeros(len(F))
        for i in range(1, len(F)):
            e[i] = 0.6 * e[i - 1] + rng.normal(0, 0.09)
        out = out + e
    return out


def ema_feats(F, taus=(1.0, 4.0, 20.0, 100.0, 400.0)):
    X = np.zeros((len(F), len(taus)))
    for j, tau in enumerate(taus):
        a = np.exp(-1 / tau)
        s = 0.0
        for i, f in enumerate(F):
            s = a * s + (1 - a) * f
            X[i, j] = s
    return X


def mlp_small(X, y, seed, h=16, it_n=3000, lr=0.01):
    r = np.random.default_rng(seed)
    mu, sd = X.mean(0), X.std(0) + 1e-9
    Xn = (X - mu) / sd
    P = [r.normal(0, 1 / np.sqrt(X.shape[1]), (X.shape[1], h)), np.zeros(h), r.normal(0, 1 / np.sqrt(h), (h, 1)),
         np.zeros(1)]
    m = [np.zeros_like(p) for p in P]
    v = [np.zeros_like(p) for p in P]
    for it in range(1, it_n + 1):
        H = np.tanh(Xn @ P[0] + P[1])
        o = (H @ P[2] + P[3])[:, 0]
        g = (2 * (o - y) / len(y))[:, None]
        gH = g @ P[2].T * (1 - H ** 2)
        for k, gr in enumerate([Xn.T @ gH, gH.sum(0), H.T @ g, g.sum(0)]):
            m[k] = 0.9 * m[k] + 0.1 * gr
            v[k] = 0.999 * v[k] + 0.001 * gr * gr
            P[k] -= lr * (m[k] / (1 - 0.9 ** it)) / (np.sqrt(v[k] / (1 - 0.999 ** it)) + 1e-8)
    return lambda Xq: (np.tanh(((Xq - mu) / sd) @ P[0] + P[1]) @ P[2] + P[3])[:, 0]


def climate():
    rng = np.random.default_rng(3)
    yrs = np.arange(1850, 2021)
    volc = np.zeros(len(yrs))
    for y0, a in [(1883, -3.0), (1902, -1.2), (1963, -1.8), (1982, -2.0), (1991, -3.2)]:
        mk = yrs >= y0
        volc[mk] += a * np.exp(-(yrs[mk] - y0) / 1.2)
    Fh = 2.7 * ((yrs - 1850) / 170.0) ** 3 + volc + 0.1 * np.sin(2 * np.pi * (yrs - 1850) / 11)
    F1p = F2X * np.arange(71) / 70.0
    Fab2 = np.full(150, F2X)
    Fab4 = np.full(150, 2 * F2X)
    fy = np.arange(2021, 2101)
    Fhigh = 2.7 + (8.5 - 2.7) * ((fy - 2020) / 80.0) ** 1.4
    Fover = np.where(fy <= 2050, 2.7 + 0.9 * (fy - 2020) / 30.0, 3.6 - 1.2 * (fy - 2050) / 50.0)

    def dataset(runs):
        return (np.concatenate([ema_feats(F) for F in runs]), np.concatenate([ebm(F, rng) for F in runs]))
    XA, yA = dataset([Fh, F1p, Fab2])
    XB, yB = dataset([Fh, F1p, Fab2, Fab4])

    def ridge(X, y, lam=1e-2):
        Xa = np.c_[X, np.ones(len(X))]
        return np.linalg.solve(Xa.T @ Xa + lam * np.eye(Xa.shape[1]), Xa.T @ y)
    wA = ridge(XA, yA)
    mA = [mlp_small(XA, yA, s) for s in range(5)]
    mB = [mlp_small(XB, yB, s) for s in range(5)]
    out = {}
    for name, Ff in [("high", Fhigh), ("over", Fover)]:
        Fall = np.concatenate([Fh, Ff])
        X = ema_feats(Fall)
        truth = ebm(Fall)
        lin = np.c_[X, np.ones(len(X))] @ wA
        pA = np.mean([f(X) for f in mA], 0)
        pB = np.mean([f(X) for f in mB], 0)
        out[name] = (Fall, truth, lin, pA, pB)
        sl = slice(-80, None)
        rm = [np.sqrt(np.mean((p[sl] - truth[sl]) ** 2)) for p in (lin, pA, pB)]
        print(f"climate {name}: T2100 truth {truth[-1]:.2f}  linear {lin[-1]:.2f}  MLP {pA[-1]:.2f}  MLP+4x "
              f"{pB[-1]:.2f}; RMSE 2021-2100 linear {rm[0]:.2f} MLP {rm[1]:.2f} MLP+4x {rm[2]:.2f}")
    print(f"climate: training forcing max {max(Fh.max(), F1p.max(), Fab2.max()):.1f} W/m2; ECS of EBM "
          f"{ebm(np.full(3000, F2X))[-1]:.2f} K; training RMSE linear "
          f"{np.sqrt(np.mean((np.c_[XA, np.ones(len(XA))] @ wA - yA) ** 2)):.3f}")
    allyr = np.arange(1850, 2101)
    fig, axs = plt.subplots(1, 3, figsize=(7.0, 2.75), gridspec_kw=dict(width_ratios=[1, 1.15, 1.15]))
    ax = axs[0]
    ax.axhspan(-3.5, F2X, color="#EEF3F8", zorder=0)
    ax.text(1856, 3.45, "range seen in training", fontsize=5.9, color=NAVY, va="top")
    ax.plot(allyr, out["high"][0], color=RED, lw=1.3, label="High-forcing test")
    ax.plot(allyr, out["over"][0], color=GREEN, lw=1.3, label="Overshoot test")
