    p_ml = clf.predict_proba(Xf[te])[:, 1]
    p_lr = Xf[te, 0]                                                       # latest log10 Pc at 2 days
    yt = y[te]

    def curve(score):
        o = np.argsort(-score)
        tp = np.cumsum(yt[o])
        al = np.arange(1, len(o) + 1)
        return al / len(o) * 1000, tp / yt.sum()

    a_lr, r_lr = curve(p_lr)
