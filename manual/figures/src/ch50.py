# Conjunction triage from synthetic CDM sequences
def pc_circ(miss, sig, R):
    """Collision probability for an isotropic 2-D Gaussian miss distribution and hard-body radius R."""
    return stats.ncx2.cdf((R / sig) ** 2, 2, (miss / sig) ** 2)


def cdm_events(rng, n=40000, D=3000.0, R=15.0):
    tk = np.arange(7.0, 0.49, -1 / 3)                                     # CDM times to TCA (days)
    nk = len(tk)
    r = D * np.sqrt(rng.uniform(size=n))
    th = rng.uniform(0, 2 * np.pi, n)
    m = np.c_[r * np.cos(th), r * np.sin(th)]
    sf = np.exp(rng.normal(np.log(60.0), 0.6, n))                         # final sigma (m)
    c = np.exp(rng.normal(np.log(2.5), 0.5, n))
    sig = sf[:, None] * (1 + c[:, None] * (tk[None, :] - 0.5) ** 1.3)       # reported sigma vs time
    kap = np.exp(rng.normal(0, 0.3, n))                                    # covariance realism (true/reported)
    z = np.zeros((n, nk, 2))
    z[:, 0] = rng.standard_normal((n, 2))
    for k in range(1, nk):
        z[:, k] = 0.75 * z[:, k - 1] + np.sqrt(1 - 0.75 ** 2) * rng.standard_normal((n, 2))
    est = m[:, None, :] + (kap[:, None] * sig)[:, :, None] * z
    miss = np.linalg.norm(est, axis=-1)
    pc = pc_circ(miss, sig, R)
    present = rng.uniform(size=(n, nk)) > 0.15
    present[:, -1] = True
    present[:, 0] = True
    return tk, miss, sig, pc, present, R


def triage_features(tk, miss, sig, pc, present, R, tcut=2.0):
    n = len(miss)
    F_ = []
    lp = np.log10(np.maximum(pc, 1e-30))
    for i in range(n):
        k = np.where(present[i] & (tk >= tcut))[0]
        mm, ss, ll = miss[i, k], sig[i, k], lp[i, k]
        kk = k[-3:]
        slope_s = np.polyfit(tk[kk], np.log(sig[i, kk]), 1)[0] if len(kk) > 1 else 0.0
        slope_m = np.polyfit(tk[kk], miss[i, kk], 1)[0] / 1000 if len(kk) > 1 else 0.0
        pmax = np.log10(min(1.0, R ** 2 / (np.e * max(mm[-1], 1.0) ** 2)))   # largest Pc for any sigma
        F_.append([ll[-1], ll.max(), ll[-1] - ll[0], mm[-1] / ss[-1], np.log10(ss[-1]), np.log10(mm[-1] + 1),
                   slope_s, slope_m, len(k), pmax, mm.std() / ss[-1]])
    return np.array(F_)


