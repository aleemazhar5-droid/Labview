    Bc = Bt * np.exp(rng.normal(0, 0.2, nobj))                             # catalogue value
    a = (RE + h) * 1e3
    nmean = np.sqrt(MU * 1e9 / a ** 3)
    k3 = 1.5 * nmean / a * np.sqrt(MU * 1e9 * a)                           # n-dot = k3 * rho * B
    rho_t = density(h[:, None], F[None, :], apl[None, :])                  # truth (lagged storm response)
    rho_e = density(h[:, None], F[None, :], ap[None, :], gain=0.65, bias=1.12)   # empirical model, no lag
    ndot_t = k3[:, None] * rho_t * Bt[:, None]                             # rad/s^2
    dt = 3600.0
    # Epochs every 24 h; horizons 6..72 h
    hz = np.array([6, 12, 24, 36, 48, 60, 72])
