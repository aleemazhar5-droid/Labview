# Synthetic catalogue shaped like the 2026 public catalogue (perigee/apogee altitudes in km)
def catalogue(n, rng):
    """Return perigee and apogee altitudes (km) of n synthetic objects and a mask of coordinated constellation members.

    Mixture: ~78 % near-circular LEO (constellation shells at 480-565 km, sun-synchronous and debris bands at
    600-1 000 km, a shell near 1 200 km), 8 % eccentric LEO debris, 3 % MEO, 5 % GTO/HEO, 6 % GEO."""
    kind = rng.choice(5, size=n, p=[0.78, 0.08, 0.03, 0.05, 0.06])
    q = np.empty(n)
    Q = np.empty(n)
    coord = np.zeros(n, bool)
    # near-circular LEO
    i = np.where(kind == 0)[0]
    comps = [(480, 8, 0.30), (545, 10, 0.08), (565, 8, 0.04), (620, 60, 0.10), (780, 45, 0.15), (860, 50, 0.13),
             (1000, 80, 0.08), (1200, 25, 0.07), (1450, 60, 0.05)]
    w = np.array([c[2] for c in comps])
    c = rng.choice(len(comps), size=len(i), p=w / w.sum())
    mu = np.array([cc[0] for cc in comps])[c]
    sd = np.array([cc[1] for cc in comps])[c]
    h = mu + sd * rng.standard_normal(len(i))
    e = np.abs(rng.normal(0, 0.0012, len(i)))
    a = RE + h
    q[i] = a * (1 - e) - RE
    Q[i] = a * (1 + e) - RE
    coord[i[c <= 2]] = True
    # eccentric LEO debris
    i = np.where(kind == 1)[0]
    qq = rng.uniform(350, 1100, len(i))
    Q[i] = qq + rng.exponential(500, len(i)) + 20
    q[i] = qq
    # MEO (navigation)
    i = np.where(kind == 2)[0]
    h = rng.choice([19100, 20180, 21530, 23220], size=len(i)) + rng.normal(0, 60, len(i))
    q[i] = h - 30
    Q[i] = h + 30
    # GTO / HEO
    i = np.where(kind == 3)[0]
    q[i] = rng.uniform(180, 800, len(i))
    Q[i] = rng.uniform(20000, 40000, len(i))
    # GEO
    i = np.where(kind == 4)[0]
    h = 35786 + rng.normal(0, 150, len(i))
    q[i] = h - np.abs(rng.normal(0, 40, len(i)))
    Q[i] = h + np.abs(rng.normal(0, 40, len(i)))
    return q, Q, coord


def overlap_pairs(q, Q, pad):
    """Number of pairs whose radial ranges [q-pad, Q+pad] overlap (exact, O(N log N))."""
    order = np.argsort(q - pad)
    s = (q - pad)[order]
    e = (Q + pad)[order]
    cnt = np.searchsorted(s, e, side="right") - np.arange(len(s)) - 1
    return int(np.sum(np.maximum(cnt, 0)))


def shell_counts(q, Q, dr=5.0, h0=150.0, h1=2500.0):
    """Objects per spherical shell of thickness dr, each object spread uniformly over its radial range."""
    grid = np.arange(h0, h1 + 1.0, 1.0)                 # 1 km grid
    diff = np.zeros(len(grid) + 1)
    keep = q < h1
    lo = np.clip(q[keep], h0, h1)
    hi = np.clip(np.maximum(Q[keep], q[keep] + 1.0), h0, h1)
    span = np.maximum(hi - lo, 1.0)
    il = np.floor(lo - h0).astype(int)
    ih = np.maximum(np.floor(hi - h0).astype(int), il + 1)
    np.add.at(diff, il, 1.0 / span)
    np.add.at(diff, ih, -1.0 / span)
    dens = np.cumsum(diff)[:-1]                         # objects per km
    k = int(dr)
    m = (len(dens) // k) * k
    occ = dens[:m].reshape(-1, k).sum(1)
    r = RE + h0 + dr * (np.arange(len(occ)) + 0.5)
    return occ, 4 * np.pi * r ** 2 * dr


def close_approaches_per_day(q, Q, coord, d_km, v_rel=10.0, dr=5.0):
    """Kinetic-gas estimate of pairs passing within d_km per day.

    Spatial density in each shell n = N_shell / V_shell; rate = sum (0.5 n_o^2 + n_c n_o) V pi d^2 v_rel, where n_c are
    coordinated constellation members (pairs inside one constellation are excluded: their orbits are designed to keep
    apart) and n_o all other objects."""
    oc, vol = shell_counts(q[coord], Q[coord], dr)
    oo, _ = shell_counts(q[~coord], Q[~coord], dr)
    nc, no = oc / vol, oo / vol
    return float(np.sum((0.5 * no ** 2 + nc * no) * vol * np.pi * d_km ** 2 * v_rel * 86400.0))


