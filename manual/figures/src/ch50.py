# Data association after a cluster deployment
GATE = 13.8           # chi-square gate, 2 degrees of freedom, 99.9 %


def assoc_trial(rng, K, ratio, sig=1.0, pdet=0.92, nclut=2):
    """One radar pass over K objects spaced ratio*sig apart along-track. Returns truth and predicted/observed points."""
    along = np.cumsum(rng.uniform(0.6, 1.4, K)) * ratio * sig
    cross = rng.normal(0, 0.15 * sig, K)
    true = np.c_[along, cross]
    S = np.array([sig, 0.25 * sig])                                      # prediction error (along, cross)
    pred = true + rng.standard_normal((K, 2)) * S
    det = rng.uniform(size=K) < pdet
    obs = true[det] + rng.standard_normal((det.sum(), 2)) * 0.05 * sig
    lab = np.where(det)[0]
    if nclut:                                                            # new fragments / unknown objects
        cl = np.c_[rng.uniform(along.min(), along.max(), nclut), rng.normal(0, 0.3 * sig, nclut)]
        obs = np.r_[obs, cl]
        lab = np.r_[lab, -np.ones(nclut, int)]
    Sc = np.sqrt(S ** 2 + (0.05 * sig) ** 2)
    d2 = (((pred[:, None, :] - obs[None, :, :]) / Sc) ** 2).sum(-1)      # Mahalanobis distance squared
    return true, pred, obs, lab, d2


def assign_greedy(d2):
    K, M = d2.shape
    a = -np.ones(K, int)
    used = np.zeros(M, bool)
    for k in range(K):                                                   # one track at a time, in catalogue order
        c = np.where(used, np.inf, d2[k])
        j = int(np.argmin(c))
        if c[j] < GATE:
            a[k] = j
            used[j] = True
    return a


def assign_global(d2):
    K, M = d2.shape
    big = 1e6
    C = np.full((K, M + K), big)
    C[:, :M] = np.where(d2 < GATE, d2, big)
    C[np.arange(K), M + np.arange(K)] = GATE                              # "not observed" option
    r, c = linear_sum_assignment(C)
    a = -np.ones(K, int)
    ok = c < M
    a[r[ok]] = c[ok]
    a[(a >= 0) & (d2[np.arange(K), np.maximum(a, 0)] >= GATE)] = -1
    return a


def score(a, lab, K):
    """Fraction of objects whose association decision is right (right observation, or correctly left unassociated)."""
    right = 0
    for k in range(K):
        if a[k] >= 0:
            right += lab[a[k]] == k
        else:
            right += k not in lab
    return right / K


def assoc():
    rng = np.random.default_rng(11)
    K = 24
    ratios = np.array([0.5, 0.75, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0, 8.0])
    g, h = [], []
    for rt in ratios:
        sg = sh = 0.0
