# Storm-time drag and a hybrid physics + machine-learning correction of along-track errors
def space_weather(rng, days=240):
    """Hourly F10.7 and Ap with random storms (synthetic)."""
    t = np.arange(days * 24) / 24.0
    F = 140 + 22 * np.sin(2 * np.pi * t / 27.0) + 10 * np.sin(2 * np.pi * t / 160.0 + 1.0)
    F += np.convolve(rng.normal(0, 4, len(t)), np.ones(48) / 48, mode="same") * 6
    ap = 6 * np.exp(rng.normal(0, 0.45, len(t)))
    ap = np.convolve(ap, np.ones(6) / 6, mode="same")
    onsets = np.sort(rng.uniform(5, days - 3, int(days / 11)))
    peaks = np.exp(rng.normal(np.log(55), 0.7, len(onsets)))
    onsets = np.r_[onsets, 196.3, 92.4]                                    # two large storms (train and test)
    peaks = np.r_[peaks, 330.0, 260.0]
    for t0, pk in zip(onsets, peaks):
        dt = t - t0
        prof = np.where(dt < 0, 0, np.where(dt < 0.15, dt / 0.15, np.exp(-(dt - 0.15) / 0.7)))
        ap += pk * prof
    return t, F, ap


def density(h, F, ap_eff, gain=1.0, bias=1.0):
    """Synthetic thermospheric density (kg/m3): quiet profile set by F10.7, storm factor set by effective Ap."""
    H = 52 + 0.18 * (F - 140)
    rho0 = 2.6e-12 * np.exp((F - 140) / 75.0)
    G = gain * (0.45 + 0.0007 * (h - 300))
    return bias * rho0 * np.exp(-(h - 400) / H) * np.exp(G * np.log1p(ap_eff / 15.0))


def lagged(ap, tau_h=5.0, delay_h=3):
    k = np.exp(-np.arange(0, 48) / tau_h)
    k /= k.sum()
    y = np.convolve(ap, k)[:len(ap)]
    return np.r_[np.full(delay_h, y[0]), y[:-delay_h]]


def drag(want_print=True):
    rng = np.random.default_rng(2024)
    t, F, ap = space_weather(rng)
    apl = lagged(ap)
    nh = len(t)
    nobj = 160
    h = rng.uniform(350, 650, nobj)
    Bt = rng.uniform(0.006, 0.03, nobj)                                    # true Cd*A/m (m2/kg)
    Bc = Bt * np.exp(rng.normal(0, 0.2, nobj))                             # catalogue value
    a = (RE + h) * 1e3
    nmean = np.sqrt(MU * 1e9 / a ** 3)
    k3 = 1.5 * nmean / a * np.sqrt(MU * 1e9 * a)                           # n-dot = k3 * rho * B
    rho_t = density(h[:, None], F[None, :], apl[None, :])                  # truth (lagged storm response)
    rho_e = density(h[:, None], F[None, :], ap[None, :], gain=0.65, bias=1.12)   # empirical model, no lag
    ndot_t = k3[:, None] * rho_t * Bt[:, None]                             # rad/s^2
    dt = 3600.0
    # Epochs every 24 h; horizons 6..72 h
    hz = np.array([6, 12, 24, 36, 48, 60, 72])
    ep = np.arange(72, nh - 80, 24)
    X, Y, E_phys, E_fit, meta, SC = [], [], [], [], [], []
    for e0 in ep:
        # drag scale fitted from the past 48 h of tracking (classical orbit determination)
        past = slice(e0 - 48, e0)
        ndot_e_past = k3[:, None] * rho_e[:, past] * Bc[:, None]
        kfit = ndot_t[:, past].sum(1) / ndot_e_past.sum(1)
        apn = ap[e0]
        rho_f = density(h[:, None], F[e0], np.full((1, 72), apn), gain=0.65, bias=1.12)   # Ap persistence
        nd_true = ndot_t[:, e0:e0 + 72]
        nd_phys = k3[:, None] * rho_f * Bc[:, None]
        nd_fit = nd_phys * kfit[:, None]
        for nd_m, store in ((nd_phys, E_phys), (nd_fit, E_fit)):
            dn = np.cumsum((nd_true - nd_m) * dt, axis=1)                  # mean-motion error (rad/s)
            du = np.cumsum(dn * dt, axis=1)                                # along-track angle error (rad)
            store.append(a[:, None] * du[:, hz - 1] / 1e3)                 # km
        one = np.ones(nobj)
        feats = np.c_[h / 300 - 1.6, np.log(Bc / 0.015), np.log(kfit), one * np.log1p(apn) / 3,
                      one * np.log1p(ap[e0 - 24:e0].mean()) / 3, one * np.log1p(ap[e0 - 48:e0].max()) / 3,
                      one * (F[e0] - 140) / 30]
        X.append(feats)
        meta.append(np.full(nobj, t[e0]))
        SC.append(0.5 * a * nd_fit[:, 0] * 86400.0 ** 2 / 1e3)             # km/day^2 drag scale of this forecast
    E_phys = np.array(E_phys)                                              # (epochs, obj, horizons)
    E_fit = np.array(E_fit)
    X = np.array(X)
    T0 = np.array(meta)
    tau = hz / 24.0
    ne, no, nz = E_fit.shape
    Xf = np.concatenate([np.repeat(X[:, :, None, :], nz, axis=2),
                         np.broadcast_to(tau[None, None, :, None] - 1.5, (ne, no, nz, 1))], axis=-1)
    SC = np.array(SC)[:, :, None]
    Yf = E_fit / tau[None, None, :] ** 2 / SC                               # error relative to modelled drag
    train = (T0 < 150)[:, :, None] & np.ones(nz, bool)
    test = (T0 >= 160)[:, :, None] & np.ones(nz, bool)
    Xtr, Ytr = Xf[train], Yf[train]
    ys = np.std(Ytr)
    P = mlp_init([Xtr.shape[1], 32, 32, 1], np.random.default_rng(5))
    P = mlp_train(P, Xtr, Ytr / ys, epochs=25, lr=3e-3, rng=np.random.default_rng(6), bs=256, decay=0.88)
    pred = mlp_fwd(P, Xf.reshape(-1, Xf.shape[-1]))[-1][:, 0].reshape(ne, no, nz) * ys
    E_hyb = E_fit - pred * SC * tau[None, None, :] ** 2

    def stats_(E, q):
        return np.array([np.quantile(np.abs(E[:, :, k][test[:, :, k]]), q) for k in range(nz)])

    out = {}
    for name, E in (("catalogue", E_phys), ("fitted", E_fit), ("hybrid", E_hyb)):
        out[name] = (stats_(E, 0.5), stats_(E, 0.9))
        if want_print:
            print(f"drag {name:9s} median |err| (km) at", dict(zip(hz, np.round(out[name][0], 2))),
                  " p90 at 72 h", round(out[name][1][-1], 2))
    # storm-window statistics (test epochs within 2 days after the big test storm onset at day 196.3)
    apmax48 = np.array([ap[e0 - 48:e0 + 1].max() for e0 in ep])
    sw = ((apmax48 > 80)[:, None] & (T0 >= 160))
    stormstats = {}
    for name, E in (("catalogue", E_phys), ("fitted", E_fit), ("hybrid", E_hyb)):
        stormstats[name] = np.array([np.median(np.abs(E[:, :, k][sw])) for k in range(nz)])
        if want_print:
            print(f"drag storm epochs ({sw[:, 0].sum()} of {(T0[:, 0] >= 160).sum()}) {name}: median |err| at 24 h "
                  f"{stormstats[name][2]:.2f} km, 72 h {stormstats[name][6]:.2f} km")
    k400 = np.argmin(np.abs(h - 450))
    i0, i1 = int(190 * 24), int(202 * 24)
    ratio_peak = (rho_t[k400] / density(h[k400], F, np.full(nh, 6.0)))[i0:i1].max()
    if want_print:
        print(f"drag: true density at {h[k400]:.0f} km peaks at {ratio_peak:.1f}x its quiet value in the test storm")

    fig = plt.figure(figsize=(7.0, 2.9))
    gs = fig.add_gridspec(2, 2, height_ratios=[1, 2.4], width_ratios=[1.15, 1], hspace=0.08, wspace=0.32)
    axa = fig.add_subplot(gs[0, 0])
    ax1 = fig.add_subplot(gs[1, 0], sharex=axa)
    ax2 = fig.add_subplot(gs[:, 1])
    tt = t[i0:i1]
    axa.fill_between(tt, ap[i0:i1], color=GOLD, alpha=0.6, lw=0)
    axa.set_ylabel("Ap", fontsize=6.6)
    axa.tick_params(labelbottom=False, labelsize=6)
    axa.set_ylim(0, 360)
    panel_tag(axa, "a", y=1.0)
    q = density(h[k400], F, np.full(nh, 6.0))
    ax1.plot(tt, (rho_t[k400] / q)[i0:i1], color=NAVY, lw=1.4, label="truth (synthetic)")
    ax1.plot(tt, (rho_e[k400] / q)[i0:i1], color=ORANGE, lw=1.2, ls="--", label="empirical model with measured Ap")
    ax1.set_ylabel(f"Density / quiet\nat {h[k400]:.0f} km")
    ax1.set_xlabel("Day of synthetic record")
    ax1.legend(fontsize=5.8, loc="upper left", frameon=False)
    ax1.grid(alpha=0.3)
    for name, c, lab in (("catalogue", GREY, "catalogue drag, no fit"), ("fitted", BLUE, "drag scale fitted to 48 h"),
                         ("hybrid", GREEN, "fitted + neural-net correction")):
        md, p90 = out[name]
        ax2.plot(hz, md, "-o", color=c, ms=3, lw=1.4, label=lab)
        ax2.plot(hz, stormstats[name], "--", color=c, lw=1.1)
    ax2.set_yscale("log")
    ax2.set_xlabel("Prediction horizon (h)")
    ax2.set_ylabel("Along-track error (km)")
    ax2.set_xticks([6, 24, 48, 72])
    ax2.grid(alpha=0.3, which="both")
    ax2.legend(fontsize=5.8, loc="lower right", frameon=False, title="median: solid, all test epochs;\ndashed, epochs after storms",
               title_fontsize=5.6)
    panel_tag(ax2, "b")
    foot(fig, f"{nobj} synthetic objects at 350–650 km over a 240-day record with random storms. Truth: density with a "
              "lagged storm response; empirical model: weaker, unlagged response. Forecasts assume Ap persists. "
              "Network (2 × 32 tanh, numpy) trained on days 3–150, tested on days 160–236.", width=140)
    fig.subplots_adjust(left=0.1, right=0.98, top=0.95, bottom=0.27)
    save(fig, "ch50_drag")


