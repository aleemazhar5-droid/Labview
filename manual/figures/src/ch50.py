# Small numpy multilayer perceptron with Adam (tanh hidden layers, linear output)
def mlp_init(sizes, rng):
    return [[rng.normal(0, np.sqrt(1.0 / a), (a, b)), np.zeros(b)] for a, b in zip(sizes[:-1], sizes[1:])]


def mlp_fwd(P, X):
    hs = [X]
    for i, (W, b) in enumerate(P):
        z = hs[-1] @ W + b
        hs.append(np.tanh(z) if i < len(P) - 1 else z)
    return hs


def mlp_train(P, X, Y, epochs, lr, rng, bs=128, decay=0.9, l2=1e-5):
    m = [[np.zeros_like(W), np.zeros_like(b)] for W, b in P]
    v = [[np.zeros_like(W), np.zeros_like(b)] for W, b in P]
    t = 0
    n = len(X)
    for _ in range(epochs):
        idx = rng.permutation(n)
        for s in range(0, n, bs):
            j = idx[s:s + bs]
            hs = mlp_fwd(P, X[j])
            g = (2.0 * (hs[-1][:, 0] - Y[j]) / len(j))[:, None]
            t += 1
            for i in range(len(P) - 1, -1, -1):
                W, b = P[i]
                grads = (hs[i].T @ g + l2 * W, g.sum(0))
                if i > 0:
                    g = (g @ W.T) * (1 - hs[i] ** 2)
                for q in range(2):
                    m[i][q] = 0.9 * m[i][q] + 0.1 * grads[q]
                    v[i][q] = 0.999 * v[i][q] + 0.001 * grads[q] ** 2
                    P[i][q] -= lr * (m[i][q] / (1 - 0.9 ** t)) / (np.sqrt(v[i][q] / (1 - 0.999 ** t)) + 1e-8)
        lr *= decay
    return P


